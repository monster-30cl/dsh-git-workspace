/**
 * `sidebarGitHistory` namespace dictionaries, and the namespace's declaration.
 *
 * The failure lines name what the history could not read, one code each, so a
 * missing Git binary, a gone Workspace, and a refused `git log` each suggest a
 * different next step. The namespace merge lives with its key set so that any
 * module naming `TranslateNS<'sidebarGitHistory'>` or
 * `PropsLocale<'sidebarGitHistory'>` needs only this file.
 */
